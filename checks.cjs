const assert = require('node:assert/strict');
const b = require('./dist/engine');
const ask = (text, previous=b.base) => b.analyze(b.parse(text, previous));
const all = b.analyze(b.base);
assert.equal(b.rows.length, 2016);
assert.equal(all.groups.length, 10);
assert.equal(all.summary.good, 6658);
assert.equal(all.summary.plan, 7296);
assert.equal(all.summary.rate, 100*406/(6658+406));
assert.equal(all.summary.load, 100*(60*4*60-573)/(60*4*60));
assert.equal(all.summary.avg,6658/60);
const lag=ask('Покажи, где выпуск сильно отстаёт от плана и какой там процент брака за последние 5 смен');
assert.equal(lag.groups.length,2);
assert.equal(lag.groups[0].v.good,469);
assert.equal(lag.groups[0].v.plan,720);
assert(lag.groups.every(g=>g.v.dev<=-10));
assert(lag.groups[0].v.dev<lag.groups[1].v.dev);
assert.equal(ask('Покажи только ночные смены',lag.q).groups.length,0);
assert.equal(ask('Покажи только ночные смены').groups.length,6);
const top=ask('Выведи топ-3 станка по доле брака');
assert.equal(top.groups.length,3);
assert(top.groups.every((g,i,a)=>!i||g.v.rate<=a[i-1].v.rate));
const comparison=ask('Сравни с прошлой неделей',top.q);
const ids=new Set(top.groups.map(g=>g.r.machine));
const baseline=b.rows.filter(r=>r.s>=23&&r.s<=27&&ids.has(r.machine));
assert.equal(comparison.previous.good,b.sum(baseline).good);
assert.equal(comparison.previous.rate,b.sum(baseline).rate);
const incidents=ask('Покажи простои длиннее 30 минут с причиной');
assert.equal(incidents.incidents.length,9);
assert(incidents.incidents.every(r=>r.down>30&&r.reason&&(r.end-r.begin)/60000===r.down));
assert.equal(incidents.incidents[0].machine,'S-102');
assert.equal(incidents.incidents[0].down,45);
const active=ask('Выпуск по активным заказам на станке S-102');
assert(active.selected.length&&active.selected.every(r=>r.status==='Активен'&&r.machine==='S-102'));
const partial=ask('Брак по причине поверхность на линии Б');
assert.equal(partial.summary.bad,partial.selected.reduce((s,r)=>s+r.parts[1],0));
assert.equal(partial.summary.rate,100*partial.summary.bad/(partial.summary.good+partial.summary.allBad));
const byDate=ask('Выпуск по часам на линии А за 17.11.2026');
assert.equal(b.trend(byDate,true).length,24);
assert.equal(b.trend(all,true).length,60);
assert.equal(b.trend(all,false).length,5);
assert.equal(ask('Выпуск за 2025-03-01').summary.rate,null);
assert.equal(ask('Сравни с прошлой неделей за последние 42 смены').previous.capacity,0);
assert.equal(ask('Средний выпуск за час').summary.avg,6658/60);
assert.throws(()=>ask('Покажи выпуск за 43 смены'));
assert.throws(()=>ask('Покажи выпуск S-999'));
assert.throws(()=>ask('Выпуск за 2026-02-30'));
assert.throws(()=>ask('Какой прогноз погоды в Казани?'));
console.log('Проверены формулы, отбор смен, рейтинг, недельное сравнение, простои, статусы, причины брака и границы данных.');
